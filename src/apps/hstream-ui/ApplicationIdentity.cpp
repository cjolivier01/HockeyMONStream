constexpr auto kManagedLauncher = "# Generated by HStream for an uninstalled command-line build.\n";

QByteArray read_file(const QString& path) {
  QFile file(path);
  return file.open(QIODevice::ReadOnly) ? file.readAll() : QByteArray{};
}

QString save_if_changed(const QString& path, const QByteArray& contents) {
  if (read_file(path) == contents)
    return {};
  if (!QDir().mkpath(QFileInfo(path).absolutePath()))
    return "could not create desktop integration directory for " + path;
  QSaveFile file(path);
  if (!file.open(QIODevice::WriteOnly) || file.write(contents) != contents.size() || !file.commit())
    return "could not save " + path + ": " + file.errorString();
  return {};
}

QString desktop_string(QString value) {
  value.replace('\\', "\\\\");
  value.replace('\n', "\\n");
  value.replace('\r', "\\r");
  value.replace('\t', "\\t");
  return value;
}

QString desktop_command(QString path) {
  // Desktop Entry string escaping is applied before Exec argument unquoting.
  // GIO checks the executable before expanding %% field codes. Use env for
  // literal-percent paths so the actual program is expanded as an argument.
  const QString prefix = path.contains('%') ? "/usr/bin/env -- " : "";
  path.replace('\\', "\\\\");
  path.replace('"', "\\\"");
  path.replace('$', "\\$");
  path.replace('`', "\\`");
  path.replace('%', "%%");
  return prefix + desktop_string('"' + path + '"');
}

